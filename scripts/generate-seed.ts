/**
 * Writes supabase/seed.sql from the content files, so the database starts with the same
 * press coverage and Security Insights that the site shows in local development.
 *
 *   npm run db:seed-sql
 */
import { writeFileSync } from "node:fs";
import { seedInsights, seedMedia } from "../src/content/articles.ts";

const q = (v: unknown) =>
  v === null || v === undefined ? "null" : typeof v === "number" ? String(v) : `'${String(v).replace(/'/g, "''")}'`;

const rows = [...seedMedia, ...seedInsights].map(
  (a) =>
    `  (${[
      q(a.kind),
      q(a.slug),
      q(a.title),
      q(a.excerpt),
      q(a.body ?? null),
      q(a.category ?? null),
      q(a.publication ?? null),
      q(a.sourceUrl ?? null),
      q(a.publishedAt),
      q(a.dateLabel ?? null),
      q(a.readingMinutes ?? null),
      q("published"),
    ].join(", ")})`,
);

const sql = `-- Generated by scripts/generate-seed.ts. Do not edit by hand.
insert into public.articles
  (kind, slug, title, excerpt, body, category, publication, source_url, published_at, date_label, reading_minutes, status)
values
${rows.join(",\n")}
on conflict (slug) do nothing;
`;

writeFileSync(new URL("../supabase/seed.sql", import.meta.url), sql);
console.log(`Wrote supabase/seed.sql with ${rows.length} articles.`);
